-- ── 1. CONSTITUENCIES ────────────────────────────────────────
CREATE TABLE IF NOT EXISTS constituencies (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    state       VARCHAR(100) NOT NULL,
    description TEXT,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ── 2. VOTERS ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS voters (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voter_id        VARCHAR(20)  NOT NULL UNIQUE,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    full_name       VARCHAR(150),
    email           VARCHAR(100) NOT NULL UNIQUE,
    phone           VARCHAR(20),
    dob             DATE,
    gender          VARCHAR(10) CHECK (gender IN ('male','female','other')),
    address         TEXT,
    state           VARCHAR(100),
    district        VARCHAR(100),
    constituency_id INTEGER REFERENCES constituencies(id) ON DELETE SET NULL,
    photo           VARCHAR(255),
    is_verified     SMALLINT NOT NULL DEFAULT 0 CHECK (is_verified IN (0,1)),
    is_admin        SMALLINT NOT NULL DEFAULT 0 CHECK (is_admin IN (0,1)),
    password        VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ── 3. ELECTIONS ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS elections (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    description     TEXT,
    start_date      TIMESTAMP NOT NULL,
    end_date        TIMESTAMP NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'draft'
                        CHECK (status IN ('draft','upcoming','active','completed')),
    show_results    SMALLINT NOT NULL DEFAULT 0 CHECK (show_results IN (0,1)),
    constituency_id INTEGER REFERENCES constituencies(id) ON DELETE SET NULL,
    created_by      INTEGER REFERENCES voters(id)         ON DELETE SET NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ── 4. CANDIDATES ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS candidates (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    party           VARCHAR(100) NOT NULL,
    party_logo      VARCHAR(255),
    symbol          VARCHAR(255),
    constituency_id INTEGER REFERENCES constituencies(id) ON DELETE SET NULL,
    election_id     INTEGER REFERENCES elections(id)      ON DELETE SET NULL,
    age             INTEGER CHECK (age IS NULL OR age BETWEEN 18 AND 120),
    education       VARCHAR(200),
    bio             TEXT,
    manifesto       TEXT,
    status          VARCHAR(10) NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active','inactive')),
    photo           VARCHAR(255),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ── 5. VOTES ─────────────────────────────────────────────────
-- The UNIQUE constraint is load-bearing: vote.php relies on catching the
-- resulting PDOException to block a double vote under a race.
CREATE TABLE IF NOT EXISTS votes (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    election_id  INTEGER NOT NULL REFERENCES elections(id)   ON DELETE CASCADE,
    voter_id     INTEGER NOT NULL REFERENCES voters(id)      ON DELETE CASCADE,
    candidate_id INTEGER NOT NULL REFERENCES candidates(id)  ON DELETE CASCADE,
    voted_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_voter_election UNIQUE (voter_id, election_id)
);

-- ── 6. ANNOUNCEMENTS ─────────────────────────────────────────
CREATE TABLE IF NOT EXISTS announcements (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200) NOT NULL,
    body       TEXT NOT NULL,
    type       VARCHAR(10) NOT NULL DEFAULT 'info'
                   CHECK (type IN ('info','success','warning','danger')),
    is_active  SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
    created_by INTEGER REFERENCES voters(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ── 7. INDEXES ───────────────────────────────────────────────
-- Every results/dashboard page runs correlated COUNT(*) subqueries over
-- votes filtered by candidate_id + election_id.
CREATE INDEX IF NOT EXISTS idx_votes_candidate_election ON votes (candidate_id, election_id);
CREATE INDEX IF NOT EXISTS idx_votes_election           ON votes (election_id);
CREATE INDEX IF NOT EXISTS idx_votes_voter              ON votes (voter_id);
CREATE INDEX IF NOT EXISTS idx_candidates_election      ON candidates (election_id);
CREATE INDEX IF NOT EXISTS idx_candidates_constituency  ON candidates (constituency_id);
CREATE INDEX IF NOT EXISTS idx_candidates_status        ON candidates (status);
CREATE INDEX IF NOT EXISTS idx_voters_constituency      ON voters (constituency_id);
CREATE INDEX IF NOT EXISTS idx_elections_status_window  ON elections (status, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_announcements_active     ON announcements (is_active, created_at DESC);

