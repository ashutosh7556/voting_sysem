-- ── 12. RESYNC IDENTITY SEQUENCES ────────────────────────────
-- Required because sections 8–9 inserted explicit ids, which does not
-- advance the identity sequence. Without this the next INSERT from the
-- admin panel fails with a duplicate-key error on id.
SELECT setval(pg_get_serial_sequence('constituencies', 'id'), COALESCE((SELECT MAX(id) FROM constituencies), 1));
SELECT setval(pg_get_serial_sequence('elections',      'id'), COALESCE((SELECT MAX(id) FROM elections),      1));
SELECT setval(pg_get_serial_sequence('candidates',     'id'), COALESCE((SELECT MAX(id) FROM candidates),     1));
SELECT setval(pg_get_serial_sequence('announcements',  'id'), COALESCE((SELECT MAX(id) FROM announcements),  1));
SELECT setval(pg_get_serial_sequence('voters',         'id'), COALESCE((SELECT MAX(id) FROM voters),         1));
SELECT setval(pg_get_serial_sequence('votes',          'id'), COALESCE((SELECT MAX(id) FROM votes),          1));

