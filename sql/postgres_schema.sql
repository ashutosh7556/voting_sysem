-- VOTING SYSTEM — POSTGRESQL / SUPABASE SCHEMA
-- Run once in the Supabase SQL Editor on a fresh database.
-- Re-runnable: every statement is guarded.
--
-- Replaces database_setup.sql + migration.sql, which are MySQL-only
-- (AUTO_INCREMENT / ENUM / TINYINT / INSERT IGNORE / USE) and cannot
-- run here.
--
-- DESIGN NOTE — why SMALLINT and not BOOLEAN for the flag columns:
-- the PHP layer writes and compares these as integers, e.g.
--   WHERE is_admin = 0          (admin/index.php, index.php)
--   SET is_verified = 1         (admin/voters.php)
--   SET is_active = 1 - is_active   (admin/announcements.php)
-- Postgres BOOLEAN rejects `= 0` with "operator does not exist:
-- boolean = integer", and `1 - is_active` has no boolean equivalent.
-- SMALLINT behaves identically on MySQL and Postgres, so the same PHP
-- runs unchanged against both. Values are constrained to 0/1 below.
-- ============================================================

